#!/bin/sh
# Install the `veystrix` command: a tiny launcher that runs this checkout's CLI.
#   scripts/install_cli.sh            -> ~/.local/bin/veystrix
#   scripts/install_cli.sh /some/bin  -> /some/bin/veystrix
# Re-run after moving the checkout. `veystrix` then starts the engine and the UI by itself;
# `veystrix engine cpp|python` swaps engines; `veystrix --help` lists everything.
set -eu
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
DEST_DIR="${1:-$HOME/.local/bin}"
PY="$ROOT/.venv/bin/python"
[ -x "$PY" ] || { echo "install_cli: $PY not found; run ./chat.sh setup first" >&2; exit 1; }
mkdir -p "$DEST_DIR"
TARGET="$DEST_DIR/veystrix"
cat > "$TARGET" <<LAUNCH
#!/bin/sh
# Generated by scripts/install_cli.sh. Runs the Veystrix checkout at:
ROOT="$ROOT"
# The venv may carry an editable install of another checkout; this checkout must win from any cwd.
PYTHONPATH="\$ROOT\${PYTHONPATH:+:\$PYTHONPATH}" exec "\$ROOT/.venv/bin/python" -m veystrix "\$@"
LAUNCH
chmod 755 "$TARGET"
echo "installed $TARGET -> $ROOT"
case ":$PATH:" in *":$DEST_DIR:"*) ;; *) echo "note: $DEST_DIR is not on PATH; add it to your shell profile." ;; esac
